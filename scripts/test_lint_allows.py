"""Tests of the allowance gate (`lint_allows.py`):

    python3 -I -m unittest discover -s scripts -p 'test_*.py'
"""

import textwrap
import unittest

import lint_allows


def rust(text: str) -> str:
    return textwrap.dedent(text).lstrip("\n")


class Allowances(unittest.TestCase):
    def test_inner_outer_and_multi_line_lists(self):
        src = rust(
            """
            #![allow(
                clippy::float_cmp, // the game's compare
                clippy::cast_sign_loss
            )]
            #[allow(clippy::too_many_arguments)]
            fn a() {}
            """
        )
        found = lint_allows.allowances(src)
        self.assertEqual(
            found,
            [
                (1, "inner", "clippy::float_cmp"),
                (1, "inner", "clippy::cast_sign_loss"),
                (5, "outer", "clippy::too_many_arguments"),
            ],
        )

    def test_expect_and_cfg_attr_count_and_comments_do_not(self):
        src = rust(
            """
            // #[allow(dead_code)]
            /// `#[allow(unused)]` in a doc
            #[expect(clippy::eq_op, reason = "a NaN test")]
            #[cfg_attr(test, allow(clippy::maybe_infinite_iter))]
            fn a() { let s = "#[allow(unused)]"; }
            """
        )
        self.assertEqual(
            lint_allows.allowances(src),
            [(3, "outer", "clippy::eq_op"), (4, "outer", "clippy::maybe_infinite_iter")],
        )

    def test_a_generated_file_keeps_its_generators_list(self):
        src = "// Generated by layout\n#![allow(missing_docs)]\n"
        self.assertEqual(lint_allows.allowances(src), [])


class Workspace(unittest.TestCase):
    def test_the_lints_the_manifest_allows(self):
        toml = rust(
            """
            [workspace.lints.rust]
            unsafe_code = "forbid"
            unreachable_pub = "allow"

            [workspace.lints.clippy]
            pedantic = { level = "warn", priority = -1 }
            module_name_repetitions = "allow"
            nursery = { level = "allow", priority = -1 }
            """
        )
        self.assertEqual(
            lint_allows.workspace_allowances(toml),
            ["clippy::module_name_repetitions", "clippy::nursery", "unreachable_pub"],
        )


class Gate(unittest.TestCase):
    def test_a_new_pair_and_a_grown_count_fail_a_shrunk_one_passes(self):
        held = {"clippy::eq_op": {"a.rs": 2}, "dead_code": {"b.rs": 1}}
        now = {"clippy::eq_op": {"a.rs": 3}, "dead_code": {"b.rs": 0}, "unused": {"c.rs": 1}}
        self.assertEqual(
            lint_allows.gate(now, held),
            [
                "a.rs: 3 allow(clippy::eq_op), was 2",
                "c.rs: 1 allow(unused), new",
            ],
        )

    def test_counts_by_lint_and_file(self):
        found = {
            "a.rs": [(1, "outer", "dead_code"), (4, "outer", "dead_code")],
            "b.rs": [(2, "inner", "unused")],
        }
        self.assertEqual(
            lint_allows.counts(found),
            {"dead_code": {"a.rs": 2}, "unused": {"b.rs": 1}},
        )


if __name__ == "__main__":
    unittest.main()
