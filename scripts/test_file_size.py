"""Tests of the file-length gate (`file_size.py`):

    python3 -I -m unittest discover -s scripts -p 'test_*.py'
"""

import os
import subprocess
import tempfile
import textwrap
import unittest
from pathlib import Path

import file_size


def rust(text: str) -> str:
    return textwrap.dedent(text).lstrip("\n")


class Mask(unittest.TestCase):
    def test_comments_and_strings_go_but_their_lines_stay(self):
        src = 'a { // }\n/* { /* } */ } */ b "{\\"}" c\n'
        code = file_size.mask(src)
        self.assertEqual(len(code), len(src))
        self.assertEqual(code.count("\n"), 2)
        self.assertEqual(code.count("{"), 1)
        self.assertEqual(code.count("}"), 0)
        self.assertIn("b", code)
        self.assertIn("c", code)

    def test_raw_strings_hold_quotes_and_braces(self):
        code = file_size.mask('x = r#"a "}" b"#; y = br"{"; z')
        self.assertEqual(code.count("{") + code.count("}"), 0)
        self.assertEqual(code.count(";"), 2)
        self.assertTrue(code.endswith(" z"))

    def test_char_literals_go_and_lifetimes_stay(self):
        code = file_size.mask("f('{', '\\'', '\\u{7d}') -> &'a T { '}' }")
        self.assertEqual(code.count("{"), 1)
        self.assertEqual(code.count("}"), 1)
        self.assertIn("'a T", code)


class TestItems(unittest.TestCase):
    def test_an_inline_test_module_with_its_doc_comment(self):
        src = rust(
            """
            fn a() {}

            /// The tests.
            #[cfg(test)]
            mod tests {
                fn b() { let s = "}"; }
            }
            fn c() {}
            """
        )
        lines, modules = file_size.test_items(src)
        self.assertEqual(sorted(lines), [3, 4, 5, 6, 7])
        self.assertEqual(modules, [])
        self.assertEqual(file_size.production_lines(src), 3)

    def test_test_only_helpers_and_declared_test_modules(self):
        src = rust(
            """
            impl X {
                #[cfg(test)]
                #[allow(dead_code)]
                pub fn only(&self) -> [u8; 2] {
                    [0; 2]
                }
                fn kept(&self) {}
            }
            #[cfg(test)]
            pub(crate) mod tests;
            #[cfg(test)]
            const N: [u8; 2] = [1, 2];
            """
        )
        lines, modules = file_size.test_items(src)
        self.assertEqual(sorted(lines), [2, 3, 4, 5, 6, 9, 10, 11, 12])
        self.assertEqual(modules, ["tests"])
        self.assertEqual(file_size.production_lines(src), 3)

    def test_a_file_without_a_final_newline_counts_its_last_line(self):
        self.assertEqual(file_size.production_lines("a\nb"), 2)
        self.assertEqual(file_size.production_lines("a\nb\n"), 2)
        self.assertEqual(file_size.production_lines(""), 0)


class Measure(unittest.TestCase):
    def test_test_files_test_directories_and_generated_files_are_not_counted(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            files = {
                "src/lib.rs": "mod a;\n#[cfg(test)]\nmod tests;\nfn f() {}\n",
                "src/tests.rs": "fn t() {}\n",
                "src/a.rs": "#[cfg(test)]\nmod checks;\nfn g() {}\nfn h() {}\n",
                "src/a/checks.rs": "fn t() {}\n",
                "src/a/checks/more.rs": "fn t() {}\n",
                "src/gen.rs": "// Generated by a tool; do not edit.\nfn x() {}\n",
                "tests/whole.rs": "fn t() {}\n",
            }
            for name, text in files.items():
                (root / name).parent.mkdir(parents=True, exist_ok=True)
                (root / name).write_text(text)
            cwd = os.getcwd()
            try:
                os.chdir(root)
                lengths = file_size.measure([Path(f) for f in files])
            finally:
                os.chdir(cwd)
        self.assertEqual(lengths, {"src/a.rs": 2, "src/lib.rs": 2})

    def test_the_working_tree_s_files_tracked_or_new_but_not_ignored(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            run = lambda *a: subprocess.run(a, cwd=root, check=True, capture_output=True)
            run("git", "init", "-q")
            (root / ".gitignore").write_text("target/\n")
            for name in ["src/lib.rs", "src/new.rs", "target/x.rs", "README.md"]:
                (root / name).parent.mkdir(parents=True, exist_ok=True)
                (root / name).write_text("\n")
            run("git", "add", "src/lib.rs")
            cwd = os.getcwd()
            try:
                os.chdir(root)
                files = file_size.rust_files()
            finally:
                os.chdir(cwd)
        self.assertEqual(files, [Path("src/lib.rs"), Path("src/new.rs")])


class Gate(unittest.TestCase):
    def test_a_file_fails_above_the_threshold_unless_the_debt_list_holds_it(self):
        lengths = {"a.rs": 701, "b.rs": 900, "c.rs": 950, "d.rs": 700}
        debt = {"b.rs": 900, "c.rs": 940}
        self.assertEqual(
            file_size.gate(lengths, 700, debt),
            [
                "a.rs: 701 production lines, new above 700",
                "c.rs: 950 production lines, was 940",
            ],
        )
        self.assertEqual(len(file_size.gate(lengths, 700, None)), 3)
        self.assertEqual(file_size.gate(lengths, 1000, None), [])


