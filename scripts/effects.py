#!/usr/bin/env python3
"""The inventory of genie-core's effects (FD-045): what an object's update hands on to be done
outside it, generated into `docs/EFFECTS.md`:

    scripts/effects.py SRC [--out FILE] [--check]

Three kinds of channel carry such an effect, one section each:

- the world's outputs: each field of `ObjectOutputs` (`world/step.rs`), the `Step` field it
  takes (named in its doc as [`Step`]'s `x`), the files that emit it (`c.x`) and the
  functions of `world/` that apply it (`out.y`);
- the unit AI's effects: each variant of `unit_ai::Effect`, what the AI does to its own unit,
  and the files that name it;
- the hand-offs: a field of any other struct whose doc gives it to its caller ("the caller's",
  "for the caller"), and the files that read it.

Each row carries the first sentence of its doc and the game routines the doc names
(`FUN_…`, slots). Test files do not count. With `--check` it fails when the file is not
current.
"""

import re
import sys
from pathlib import Path

import readmes

HEADER = "<!-- Generated by scripts/effects.py (FD-045): do not edit, run `just effects`. -->"
HAND_OFF = re.compile(r"the caller's(?! use)|for the caller(?!'s use)|the caller (?:runs|sends|hands|takes|applies)")
GAME = re.compile(r"\b(?:FUN_1[0-9a-f]{8}|0x1[0-9a-f]{8}|slot 0x[0-9a-f]+)")
FIELD = re.compile(r"^\s*pub(?:\([^)]*\))? ([a-z_][a-z0-9_]*):\s*(.*)$")
TYPE_DEF = re.compile(r"^\s*pub(?:\([^)]*\))? (?:struct|enum) ([A-Z][A-Za-z0-9]*)")
VARIANT = re.compile(r"^    ([A-Z][A-Za-z0-9]*)\b")
FN = re.compile(r"\bfn ([a-z_][a-z0-9_]*)")
CONTEXT_FIELD = re.compile(r"\[`Step`\]'s `([a-z_][a-z0-9_]*)`")


def sentence(doc: list[str]) -> str:
    """A doc's first sentence on one line, as the READMEs give a module's."""
    return readmes.first_sentence("\n".join(f"//! {line}" for line in doc))


def game_refs(doc: list[str]) -> str:
    """The game routines and slots a doc names, in order, each once."""
    seen = []
    for ref in GAME.findall(" ".join(doc)):
        if ref not in seen:
            seen.append(ref)
    return ", ".join(f"`{r}`" for r in seen)


def type_text(lines: list[str], i: int, first: str) -> tuple[str, int]:
    """A field's type from its line on (it may span lines), without the closing comma, and the
    index of its last line."""
    text = first
    depth = sum(text.count(o) - text.count(c) for o, c in ("()", "<>", "[]"))
    while (depth > 0 or not text) and i + 1 < len(lines):
        i += 1
        part = lines[i].strip()
        text += part
        depth += sum(part.count(o) - part.count(c) for o, c in ("()", "<>", "[]"))
    return re.sub(r",\s*\)", ")", text).rstrip(",").strip(), i


def fields_of(text: str) -> dict[str, list[tuple[str, str, list[str]]]]:
    """Each struct's documented fields (name, type, doc lines), by struct, in order."""
    out: dict[str, list[tuple[str, str, list[str]]]] = {}
    lines = text.split("\n")
    doc: list[str] = []
    current = None
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        m = TYPE_DEF.match(line)
        if m:
            current = m.group(1)
        if s.startswith("///"):
            doc.append(s[3:].strip())
        else:
            f = FIELD.match(line)
            if f and current and doc and line.startswith("    ") and not line.startswith("     "):
                ty, i = type_text(lines, i, f.group(2))
                out.setdefault(current, []).append((f.group(1), ty, doc))
            if not s.startswith("#["):
                doc = []
        i += 1
    return out


def variants_of(text: str, enum: str) -> list[tuple[str, list[str]]]:
    """An enum's variants (name, doc lines), in order."""
    lines = text.split("\n")
    start = next(i for i, line in enumerate(lines) if re.match(rf"^pub enum {enum}\b", line))
    out = []
    doc: list[str] = []
    for line in lines[start + 1 :]:
        if line.startswith("}"):
            break
        s = line.strip()
        if line.startswith("    ///"):
            doc.append(s[3:].strip())
            continue
        m = VARIANT.match(line)
        if m:
            out.append((m.group(1), doc))
        if not line.startswith("     ") and not s.startswith("#["):
            doc = []
    return out


def sources(src: Path) -> dict[str, str]:
    """The crate's production files (path relative to `src`, text)."""
    out = {}
    for f in sorted(src.rglob("*.rs")):
        text = f.read_text()
        if not readmes.is_test(f, text):
            out[f.relative_to(src).as_posix()] = text
    return out


def files_matching(files: dict[str, str], pattern: re.Pattern, skip: str = "") -> list[str]:
    return [p for p, t in files.items() if p != skip and pattern.search(t)]


def functions_matching(text: str, pattern: re.Pattern) -> list[str]:
    """The functions of a file whose body matches, each once, in order."""
    out = []
    current = None
    for line in text.split("\n"):
        m = FN.search(line)
        if m and not line.strip().startswith("//"):
            current = m.group(1)
        if current and pattern.search(line) and current not in out:
            out.append(current)
    return out


def link(path: str, src_link: str) -> str:
    return f"[`{path}`]({src_link}/{path})"


def links(paths: list[str], src_link: str) -> str:
    return ", ".join(link(p, src_link) for p in paths)


def world_outputs(files: dict[str, str], src_link: str) -> list[str]:
    step = fields_of(files["world/step.rs"])
    by_name = {name: (ty, doc) for name, ty, doc in step.get("Step", [])}
    rows = ["| Output | Type | What it carries | Game | Emitted in | Applied in |", "| --- | --- | --- | --- | --- | --- |"]
    for name, ty, doc in step.get("ObjectOutputs", []):
        m = CONTEXT_FIELD.search(" ".join(doc))
        field = m.group(1) if m else name
        _, cdoc = by_name.get(field, (ty, doc))
        emitted = files_matching(files, re.compile(rf"\b(?:c|ctx|context)\.{field}\b"), "world/step.rs")
        applied = []
        out_use = re.compile(rf"\bout\.{name}\b")
        for path, text in files.items():
            if path.startswith("world/"):
                applied += [f"`{f}`" for f in functions_matching(text, out_use)]
        rows.append(
            f"| `{field}` | `{ty}` | {sentence(cdoc)} | {game_refs(cdoc)} | {links(emitted, src_link)} | {', '.join(applied)} |"
        )
    return rows


def unit_ai_effects(files: dict[str, str], src_link: str) -> list[str]:
    """A row per variant of `Effect`; `Effect::Command` gives a row per variant of `AiCommand`
    in its place."""
    rows = ["| Effect | What it does | Game | Named in |", "| --- | --- | --- | --- |"]
    unit_ai = files["unit_ai/mod.rs"]
    for name, doc in variants_of(unit_ai, "Effect"):
        kinds = (
            [(f"AiCommand::{c}", cdoc) for c, cdoc in variants_of(unit_ai, "AiCommand")]
            if name == "Command"
            else [(f"Effect::{name}", doc)]
        )
        for path, kdoc in kinds:
            named = files_matching(files, re.compile(rf"\b{path}\b"))
            shown = path.removeprefix("Effect::")
            rows.append(f"| `{shown}` | {sentence(kdoc)} | {game_refs(kdoc)} | {links(named, src_link)} |")
    return rows


def hand_offs(files: dict[str, str], src_link: str) -> list[str]:
    rows = ["| Struct | Field | What it carries | Game | Read in |", "| --- | --- | --- | --- | --- |"]
    for path, text in files.items():
        for struct, fields in fields_of(text).items():
            if struct in ("Step", "ObjectOutputs"):
                continue
            for name, _ty, doc in fields:
                if not HAND_OFF.search(" ".join(doc)):
                    continue
                read = files_matching(files, re.compile(rf"\.{name}\b"), path)
                rows.append(
                    f"| {link(path, src_link)} `{struct}` | `{name}` | {sentence(doc)} | {game_refs(doc)} | {links(read, src_link)} |"
                )
    return rows


def inventory(src: Path, src_link: str) -> str:
    files = sources(src)
    outputs = world_outputs(files, src_link)
    effects = unit_ai_effects(files, src_link)
    offs = hand_offs(files, src_link)
    count = lambda rows: len(rows) - 2  # noqa: E731
    return "\n".join(
        [
            HEADER,
            "",
            "# Effects: what an object's update hands on",
            "",
            "An object's update in the game changes other objects by direct calls (a notify through",
            "slot 0x38, a release through slot 0x180, a stop through slot 0x5d0). genie-core cannot",
            "change them from inside the update, so it hands such effects on to be done outside it.",
            "These are the channels it uses (FD-045): "
            f"{count(outputs)} world outputs, {count(effects)} unit AI effects and {count(offs)} hand-offs.",
            "",
            "## The world's outputs",
            "",
            "The fields of `ObjectOutputs`: what an object's step leaves for the world, applied after",
            "the object's update by the functions named.",
            "",
            *outputs,
            "",
            "## The unit AI's effects",
            "",
            "The variants of `unit_ai::Effect`: what the unit AI does to its own unit, in its order;",
            "a command of the unit's own (`Effect::Command`) by the variants of `unit_ai::AiCommand`.",
            "",
            *effects,
            "",
            "## The hand-offs",
            "",
            "Fields a part fills for its caller to apply (their doc says \"the caller's\" or \"for the",
            "caller\").",
            "",
            *offs,
            "",
        ]
    )


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    check = "--check" in argv
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else None
    if out is not None:
        args.remove(str(out))
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    src = Path(args[0])
    out = out or Path("docs/EFFECTS.md")
    src_link = Path(*([".."] * len(out.parent.parts)), src).as_posix()
    text = inventory(src, src_link)
    if check:
        if not out.exists() or out.read_text() != text:
            print(f"{out}: not current with {src}; run `just effects`", file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
