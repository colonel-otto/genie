#!/usr/bin/env python3
"""The allowance gate (FD-043, the review checklist's section L): no lint is turned off where it
was not before.

    scripts/lint_allows.py [--check]      fails on an allowance a file did not hold before: a lint
                                          a file newly allows, or allows more often than the
                                          list (.config/lint-allows.json) holds
    scripts/lint_allows.py --report       section L's table: each lint with its count, its
                                          crates and where it is turned off (workspace, crate,
                                          module, item), no gate
    scripts/lint_allows.py --sites LINT   each place that allows LINT, as `file:line`
    scripts/lint_allows.py --bless        the list becomes this run's allowances (after one went)

An allowance is a lint named in an `allow(…)` or `expect(…)` attribute, on its own or inside a
`cfg_attr(…)`, and a lint the workspace's `Cargo.toml` sets to "allow". Comments, doc comments
and strings do not count. A generated file (its first line starts with `// Generated by` or
`//! Generated by`) keeps its generator's list and is not counted (`/work/CLAUDE.md`). The
files are those git knows of in the working tree. Python 3.11 or later, no packages.
"""

import json
import os
import re
import subprocess
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

from file_size import GENERATED, attribute_end, line_of, mask, rust_files

LIST = Path(".config/lint-allows.json")
MANIFEST = Path("Cargo.toml")
WORKSPACE = "Cargo.toml"

ATTRIBUTE = re.compile(r"#\s*(!?)\s*\[")
ALLOWING = re.compile(r"\b(?:allow|expect)\s*\(")
LINT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)*$")

Allowance = tuple[int, str, str]


def group_end(code: str, i: int) -> int:
    """The offset of the `)` that closes the group whose `(` is just before `i`."""
    depth = 1
    for j in range(i, len(code)):
        if code[j] == "(":
            depth += 1
        elif code[j] == ")":
            depth -= 1
            if depth == 0:
                return j
    return len(code)


def allowances(src: str) -> list[Allowance]:
    """Each lint `src` allows, as (line, `inner` or `outer`, lint), in the file's order."""
    if GENERATED.match(src.split("\n", 1)[0]):
        return []
    code = mask(src)
    found: list[Allowance] = []
    for attr in ATTRIBUTE.finditer(code):
        kind = "inner" if attr.group(1) else "outer"
        end = attribute_end(code, attr.end() - 1)
        line = line_of(src, attr.start())
        body = code[attr.end() : end - 1]
        for group in ALLOWING.finditer(body):
            names = body[group.end() : group_end(body, group.end())]
            for name in names.split(","):
                name = name.strip()
                if LINT.match(name):
                    found.append((line, kind, name))
    return found


def workspace_allowances(manifest: str) -> list[str]:
    """The lints the workspace manifest's `[workspace.lints.*]` tables set to "allow", sorted;
    a tool's lint carries its prefix (`clippy::…`)."""
    tables = tomllib.loads(manifest).get("workspace", {}).get("lints", {})
    out = []
    for tool, lints in tables.items():
        for name, level in lints.items():
            level = level.get("level") if isinstance(level, dict) else level
            if level == "allow":
                out.append(name if tool == "rust" else f"{tool}::{name}")
    return sorted(out)


def counts(found: dict[str, list[Allowance]]) -> dict[str, dict[str, int]]:
    """How often each lint is allowed in each file of `found`, sorted by lint and file."""
    out: dict[str, dict[str, int]] = defaultdict(dict)
    for f, sites in sorted(found.items()):
        for _, _, lint in sites:
            out[lint][f] = out[lint].get(f, 0) + 1
    return {lint: out[lint] for lint in sorted(out)}


def gate(now: dict[str, dict[str, int]], held: dict[str, dict[str, int]]) -> list[str]:
    """The allowances of `now` that `held` does not hold at that count or more, each as its
    message."""
    failures = []
    for lint, files in now.items():
        for f, n in files.items():
            was = held.get(lint, {}).get(f)
            if was is None and n:
                failures.append(f"{f}: {n} allow({lint}), new")
            elif was is not None and was < n:
                failures.append(f"{f}: {n} allow({lint}), was {was}")
    return sorted(failures)


def crate_of(path: str) -> str:
    """The crate a file of `crates/GROUP/CRATE/…` belongs to; the workspace for the rest."""
    parts = Path(path).parts
    return parts[2] if len(parts) > 2 and parts[0] == "crates" else "workspace"


def scope_of(path: str, kind: str) -> str:
    """Where an allowance turns its lint off: a crate root's inner attribute the crate, another
    inner attribute its module, an outer one its item."""
    if kind == "outer":
        return "item"
    name = Path(path).name
    under_src = "src" in Path(path).parts
    return "crate" if name in ("lib.rs", "main.rs") and under_src else "module"


def scan() -> dict[str, list[Allowance]]:
    """Each Rust file git knows of with the allowances it holds; the manifest's under
    `Cargo.toml`."""
    found = {}
    for f in rust_files():
        sites = allowances(f.read_text(encoding="utf-8"))
        if sites:
            found[str(f)] = sites
    workspace = workspace_allowances(MANIFEST.read_text(encoding="utf-8"))
    if workspace:
        found[WORKSPACE] = [(0, "workspace", lint) for lint in workspace]
    return found


def report(found: dict[str, list[Allowance]]) -> str:
    """Section L's table: each lint, how often it is allowed, in which crates, and where."""
    rows: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for f, sites in found.items():
        for _, kind, lint in sites:
            scope = "workspace" if kind == "workspace" else scope_of(f, kind)
            rows[lint].append((crate_of(f), scope))
    lines = ["| Lint | Count | Crates | Turned off for |", "| --- | --- | --- | --- |"]
    for lint, sites in sorted(rows.items(), key=lambda e: (-len(e[1]), e[0])):
        crates = sorted({c for c, _ in sites})
        scopes = defaultdict(int)
        for _, s in sites:
            scopes[s] += 1
        where = ", ".join(f"{s} {n}" for s, n in sorted(scopes.items()))
        lines.append(f"| `{lint}` | {len(sites)} | {', '.join(crates)} | {where} |")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], check=True, capture_output=True, text=True
    ).stdout.strip()
    os.chdir(root)
    mode = argv[0] if argv else "--check"
    found = scan()
    now = counts(found)
    if mode == "--report":
        print(report(found))
        return 0
    if mode == "--sites":
        if len(argv) < 2:
            print("lint-allows: --sites LINT", file=sys.stderr)
            return 2
        for f, sites in found.items():
            for line, _, lint in sites:
                if lint == argv[1]:
                    print(f"{f}:{line}")
        return 0
    if mode == "--bless":
        LIST.write_text(json.dumps(now, indent=1) + "\n", encoding="utf-8")
        total = sum(sum(files.values()) for files in now.values())
        print(f"lint-allows: {total} allowances of {len(now)} lints in {LIST}")
        return 0
    if mode != "--check":
        print(f"lint-allows: unknown mode {mode} (--check, --report, --sites, --bless)", file=sys.stderr)
        return 2
    held = json.loads(LIST.read_text(encoding="utf-8")) if LIST.exists() else {}
    failures = gate(now, held)
    if failures:
        print("\n".join(failures), file=sys.stderr)
        print(
            "lint-allows: fix the code the lint flags (FD-043, the review checklist's section L)",
            file=sys.stderr,
        )
        return 1
    total = sum(sum(files.values()) for files in now.values())
    print(f"lint-allows: no new allowance ({total} held)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
