#!/usr/bin/env python3
"""The file-length gate (`.config/file-size.toml`): no hand-written Rust file holds more
production lines than the threshold. The pre-commit hook and CI run the gate.

    scripts/file_size.py [--gate]         fails on a file above the threshold that the debt list
                                          (.config/file-size-debt.json) does not hold at that
                                          length or more; without a debt list, on any file above it
    scripts/file_size.py --report [N]     the N longest files (all without N), no gate
    scripts/file_size.py --bless          the debt list becomes this run's files above the
                                          threshold; with none, the list goes and the gate is
                                          absolute

A file's production lines are its lines outside its test code. Test code is each `#[cfg(test)]`
item with the comments and attributes right above it, the file of a `#[cfg(test)] mod name;` and
the files below it, and the `tests/` and `benches/` directories. A generated file (its first line
starts with `// Generated by` or `//! Generated by`) is not counted. The files are those git
knows of in the working tree, tracked or new but not ignored. Python 3.11 or later, no packages.
"""

import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

CONFIG = Path(".config/file-size.toml")
DEBT = Path(".config/file-size-debt.json")

GENERATED = re.compile(r"^//!? Generated by")
CFG_TEST = re.compile(r"#\s*\[\s*cfg\s*\(\s*test\s*\)\s*\]")
TEST_MOD = re.compile(r"\s*(?:pub(?:\s*\([^)]*\))?\s+)?mod\s+(\w+)\s*;")
RAW_STRING = re.compile(r"b?r(#*)\"")
TEST_DIRS = {"tests", "benches"}


def mask(src: str) -> str:
    """`src` with its comments, string literals and char literals blanked (newlines kept), so
    the brackets and semicolons left are the code's and every offset keeps its line."""
    out = list(src)
    n = len(src)

    def blank(a: int, b: int) -> None:
        for k in range(a, min(b, n)):
            if out[k] != "\n":
                out[k] = " "

    def ident(k: int) -> bool:
        return 0 <= k < n and (src[k].isalnum() or src[k] == "_")

    i = 0
    while i < n:
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            blank(i, j)
            i = j
            continue
        if src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif src.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            blank(i, j)
            i = j
            continue
        raw = RAW_STRING.match(src, i)
        if raw and not ident(i - 1):
            close = '"' + raw.group(1)
            end = src.find(close, raw.end())
            j = n if end < 0 else end + len(close)
            blank(i, j)
            i = j
            continue
        c = src[i]
        if c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            blank(i, j + 1)
            i = j + 1
            continue
        if c == "'":
            if src.startswith("\\", i + 1):
                # an escape: '\'', '\\', '\n', '\u{…}'
                end = src.find("'", i + 3)
                j = n if end < 0 else end + 1
                blank(i, j)
                i = j
                continue
            if i + 2 < n and src[i + 2] == "'":
                blank(i, i + 3)
                i += 3
                continue
            # a lifetime or a label
        i += 1
    return "".join(out)


def item_end(code: str, i: int) -> int:
    """The offset just past the item that starts at or after `i` in masked `code`: its first `;`
    outside brackets, or the `}` that closes its body; the attributes before it are skipped."""
    n = len(code)
    depth = 0
    opens, closes = "([{", ")]}"
    while i < n:
        c = code[i]
        if c in opens:
            depth += 1
        elif c in closes:
            depth -= 1
            if depth == 0 and c == "}":
                return i + 1
            if depth < 0:
                return i
        elif c == ";" and depth == 0:
            return i + 1
        i += 1
    return n


def attribute_end(code: str, i: int) -> int:
    """The offset past the attribute `#[…]` that starts at `i` in masked `code`."""
    depth = 0
    for j in range(i, len(code)):
        if code[j] == "[":
            depth += 1
        elif code[j] == "]":
            depth -= 1
            if depth == 0:
                return j + 1
    return len(code)


def line_of(src: str, offset: int) -> int:
    """The 1-based line of `offset` in `src`."""
    return src.count("\n", 0, offset) + 1


def test_items(src: str) -> tuple[set[int], list[str]]:
    """The lines of `src`'s test code (each `#[cfg(test)]` item, its doc comments and attributes
    right above it) and the names of the test modules it declares as files (`mod name;`)."""
    code = mask(src)
    lines = src.split("\n")
    test: set[int] = set()
    modules: list[str] = []
    for m in CFG_TEST.finditer(code):
        start = line_of(src, m.start())
        # the doc comments, comments and attributes right above belong to the item
        while start > 1 and lines[start - 2].lstrip().startswith(("//", "#[")):
            start -= 1
        i = m.end()
        while True:
            while i < len(code) and code[i].isspace():
                i += 1
            if not code.startswith("#", i):
                break
            i = attribute_end(code, i)
        declared = TEST_MOD.match(code, i)
        if declared:
            modules.append(declared.group(1))
        end = line_of(src, max(item_end(code, i) - 1, i))
        test.update(range(start, end + 1))
    return test, modules


def production_lines(src: str) -> int:
    """The lines of `src` outside its test code; a trailing newline ends the last line."""
    total = src.count("\n") + (0 if src.endswith("\n") or not src else 1)
    test, _ = test_items(src)
    return total - len([n for n in test if n <= total])


def module_dir(path: Path) -> Path:
    """The directory of the files of `path`'s child modules: its own for `mod.rs`, `lib.rs` and
    `main.rs`, else the one named as it beside it."""
    if path.name in ("mod.rs", "lib.rs", "main.rs"):
        return path.parent
    return path.parent / path.stem


def rust_files() -> list[Path]:
    """The `.rs` files git knows of in the working tree: tracked, or new and not ignored."""
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", "*.rs"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return sorted({Path(p) for p in out.split("\0") if p and Path(p).is_file()})


def measure(files: list[Path]) -> dict[str, int]:
    """Each hand-written production file of `files` with its production lines."""
    sources = {f: f.read_text(encoding="utf-8") for f in files}
    test_files: set[Path] = set()
    test_dirs: set[Path] = set()
    lengths: dict[Path, int] = {}
    for f, src in sources.items():
        _, modules = test_items(src)
        for name in modules:
            base = module_dir(f)
            test_files.update([base / f"{name}.rs", base / name / "mod.rs"])
            test_dirs.add(base / name)
    for f, src in sources.items():
        if TEST_DIRS.intersection(f.parts[:-1]) or f in test_files:
            continue
        if any(d in f.parents for d in test_dirs):
            continue
        if GENERATED.match(src.split("\n", 1)[0]):
            continue
        lengths[f] = production_lines(src)
    return {str(f): n for f, n in sorted(lengths.items())}


def gate(lengths: dict[str, int], threshold: int, debt: dict[str, int] | None) -> list[str]:
    """The files of `lengths` above `threshold` that `debt` does not hold at that length or more
    (without a debt list, every file above it), each as its message."""
    failures = []
    for f, n in lengths.items():
        if n <= threshold:
            continue
        allowed = None if debt is None else debt.get(f)
        if allowed is None:
            failures.append(f"{f}: {n} production lines, new above {threshold}")
        elif allowed < n:
            failures.append(f"{f}: {n} production lines, was {allowed}")
    return failures


def main(argv: list[str]) -> int:
    root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], check=True, capture_output=True, text=True
    ).stdout.strip()
    os.chdir(root)
    mode = argv[0] if argv else "--gate"
    if not CONFIG.exists():
        print(f"file-size: no {CONFIG} in {root} (its `threshold = N`)", file=sys.stderr)
        return 2
    threshold = tomllib.loads(CONFIG.read_text(encoding="utf-8"))["threshold"]
    lengths = measure(rust_files())
    above = {f: n for f, n in lengths.items() if n > threshold}
    if mode == "--report":
        top = int(argv[1]) if len(argv) > 1 else len(lengths)
        for f, n in sorted(lengths.items(), key=lambda e: (-e[1], e[0]))[:top]:
            print(f"{n:6} {f}")
        return 0
    if mode == "--bless":
        if not above:
            DEBT.unlink(missing_ok=True)
            print(f"file-size: no file above {threshold}: the debt list is gone, the gate is absolute")
            return 0
        body = {"threshold": threshold, "files": above}
        DEBT.write_text(json.dumps(body, indent=1) + "\n", encoding="utf-8")
        print(f"file-size: {len(above)} files above {threshold} in {DEBT}")
        return 0
    if mode != "--gate":
        print(f"file-size: unknown mode {mode} (--gate, --report, --bless)", file=sys.stderr)
        return 2
    debt = json.loads(DEBT.read_text(encoding="utf-8"))["files"] if DEBT.exists() else None
    failures = gate(lengths, threshold, debt)
    if failures:
        print("\n".join(failures), file=sys.stderr)
        print("file-size: split them into modules along their own structure", file=sys.stderr)
        return 1
    held = 0 if debt is None else len(debt)
    print(f"file-size: no file rose above {threshold} production lines ({held} in the debt list)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
